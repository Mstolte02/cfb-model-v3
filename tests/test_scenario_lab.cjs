const assert=require('node:assert/strict');
const L=require('../viz/scenario-lab.js');
const schedule=require('../viz/data/schedule.json'),meta=require('../viz/data/teams.json');
const ratings=require('../viz/data/ratings.json').teams,committee=require('../viz/data/cfp_rankings.json'),playoff=require('../viz/data/playoff_current.json');
const cfg={schedule,meta,ratings,committee,playoff};
const blank=L.evaluate(cfg);
assert(blank.remaining>0);assert.equal(blank.field.length,0);assert.equal(blank.titleGames.length,0);
assert(blank.rows.filter(r=>!r.locked).every(r=>r.winner===null));
const locked=blank.rows.find(r=>r.locked&&r.winner);
const poison=L.evaluate({...cfg,picks:{[locked.key]:locked.winner===locked.g.h?locked.g.a:locked.g.h}});
assert.equal(poison.rows.find(r=>r.key===locked.key).winner,locked.winner);
assert.deepEqual(poison.records,blank.records);
const picks=Object.fromEntries(blank.rows.filter(r=>!r.locked).map(r=>[r.key,r.g.h]));
const regular=L.evaluate({...cfg,picks});assert.equal(regular.remaining,0);assert(regular.titleGames.length>=4);assert.equal(regular.field.length,0);
const invalid=L.evaluate({...cfg,picks,titles:Object.fromEntries(regular.titleGames.map(t=>[t.conf,'Not a participant']))});assert(invalid.titleGames.every(t=>!t.winner));
const titles=Object.fromEntries(regular.titleGames.map(t=>[t.conf,t.h]));
const complete=L.evaluate({...cfg,picks,titles});assert(complete.complete);assert.equal(complete.field.length,12);assert.equal(new Set(complete.field.map(r=>r.team)).size,12);
for(const conf of ['ACC','Big Ten','Big 12','SEC'])assert(complete.field.some(r=>r.team===titles[conf]&&r.auto));
assert(complete.field.some(r=>r.bid==='Group of 6 bid'));
assert.equal(L.choose('H','A',.8,'favorite'),'H');assert.equal(L.choose('H','A',.8,'underdog'),'A');
assert.equal(L.choose('H','A',.8,'coin',()=>.6),'A');assert.equal(L.choose('H','A',.8,'weighted',()=>.6),'H');
const games=[{round:'R1',top:'A',bottom:'B'},{round:'QF',top:'C',bottom:null},{round:'SF',top:null,bottom:null}];
const feeds={1:[0],2:[0,1]};
let G=L.resolvePicks(games,feeds,{});assert(G.every(g=>g.winner===null));assert.equal(G[1].bottom,null);
G=L.resolvePicks(games,feeds,{0:'A'});assert.equal(G[1].bottom,'A');assert.equal(G[1].winner,null);assert.equal(G[2].bottom,null);
G=L.resolvePicks(games,feeds,{0:'B',1:'A'});assert.equal(G[1].winner,null); // stale nonparticipant cannot advance
assert(!G.some(g=>'p' in g||'sa' in g||'sb' in g));assert.equal(games[1].bottom,null);
const {effect}=require('../viz/simulation-studio.js');
const game={home:'H',away:'A',effects:{H:{home_win:.8,away_win:.3},A:{home_win:.2,away_win:.7}}};
assert.deepEqual(effect(game,'H'),{win:.8,loss:.3});assert.deepEqual(effect(game,'A'),{win:.7,loss:.2});
console.log('Scenario lab: blank state, completed-result locks, explicit title gates, 12-team rules, probability-weighted/coin selections, stale-pick rejection and winner-only advancement passed');
