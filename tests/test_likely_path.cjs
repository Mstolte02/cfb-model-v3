const assert=require('node:assert/strict');
global.PlayoffPaths=require('../viz/playoff-paths.js');
const {likelyPath}=require('../viz/simulation-studio.js');
const game=(id,swing=.6)=>({id:String(id),week:12,date:'2026-11-21',home:'A & B',away:'<Opponent>',samples_home:100,samples_away:100,supported:true,effects:{'A & B':{swing,home_win:.8,away_win:.2}}});
const render=impacts=>likelyPath('A & B',{game_impacts:impacts},{});
assert(render(null).includes('after the next season simulation'));
assert(render({baseline:{'A & B':0},games:[]}).includes('does not prove elimination'));
assert(render({baseline:{'A & B':.5},games:[game('boundary',.025)]}).includes('No remaining game has'));
const games=Array.from({length:7},(_,i)=>game(i));
games[0].supported=false;
const html=render({baseline:{'A & B':.5},games:[...games,game('excluded',.025)]});
assert(html.includes('A &amp; B beats &lt;Opponent&gt;'));
assert.equal((html.match(/data-route-game=/g)||[]).length,7);
assert(!html.includes('data-route-game="excluded"'));
assert(html.includes('Playoff probability: 20.0% with the other winner, 80.0% if A &amp; B wins'));
assert(html.includes('100 simulations · small sample'));
assert(html.includes('80.0% of qualifying seasons had this winner'));
assert(html.includes('Other winner'));
assert(html.includes('Likely qualifying winner'));
// A rare upset can boost CFP odds but still be less common in qualifying seasons.
const rare=game('rare');rare.samples_home=20;rare.samples_away=180;
const rareHTML=render({baseline:{'A & B':.26},games:[rare]});
assert(rareHTML.includes('&lt;Opponent&gt; beats A &amp; B'));
assert(rareHTML.includes('69.2% of qualifying seasons had this winner'));
assert(rareHTML.includes('80.0% with the other winner, 20.0% if &lt;Opponent&gt; wins'));
console.log('Path chart: all games above strict threshold, Bayes qualifying outcomes, per-game odds, escaping and sample flags passed');
